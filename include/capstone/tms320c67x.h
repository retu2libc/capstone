typedef enum tms320c67x_op_type {
    TMS320C67X_OP_INVALID = CS_OP_INVALID, ///< = CS_OP_INVALID (Uninitialized).
    TMS320C67X_OP_REG = CS_OP_REG, ///< = CS_OP_REG (Register operand).
    TMS320C67X_OP_IMM = CS_OP_IMM, ///< = CS_OP_IMM (Immediate operand).
    TMS320C67X_OP_REGPAIR = CS_OP_SPECIAL + 0, ///< Register pair for double word ops
    TMS320C67X_OP_MEM = CS_OP_MEM, ///< = CS_OP_MEM (Memory operand).
} tms320c67x_op_type;

