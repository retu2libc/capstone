typedef struct tms320c67x_op_mem {
    unsigned int	base;	///< base register
    unsigned int	disp;	///< displacement/offset value
    unsigned int	unit;	///< unit of base and offset register
    unsigned int	scaled;	///< offset scaled
    unsigned int	disptype;	///< displacement type
    unsigned int	direction;	///< direction
    unsigned int	modify;	///< modification
} tms320c67x_op_mem;

typedef struct cs_tms320c67x_op {
    tms320c67x_op_type type;	///< operand type
    union {
        unsigned int reg;	///< register value for REG operand or first register for REGPAIR operand
        int32_t imm;		///< immediate value for IMM operand
        tms320c67x_op_mem mem;		///< base/disp value for MEM operand
    };
} cs_tms320c67x_op;

typedef struct cs_tms320c67x {
    uint8_t op_count;
    cs_tms320c67x_op operands[8]; ///< operands for this instruction.
    struct {
        unsigned int reg;
        unsigned int zero;
    } condition;
    struct {
        unsigned int unit;
        unsigned int side;
        unsigned int crosspath;
    } funit;
    unsigned int parallel;
} cs_tms320c67x;

